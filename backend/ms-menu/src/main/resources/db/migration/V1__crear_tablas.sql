CREATE SCHEMA IF NOT EXISTS menu;

-- =============================================
-- 1. TABLA CATEGORIA
-- =============================================

CREATE TABLE menu.categoria (
    id_categoria INTEGER GENERATED BY DEFAULT AS IDENTITY,
    codigo_categoria VARCHAR(30) NOT NULL,
    nombre_categoria VARCHAR(100) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT pk_categoria PRIMARY KEY (id_categoria),
    CONSTRAINT uq_categoria_codigo UNIQUE (codigo_categoria),
    CONSTRAINT uq_categoria_nombre UNIQUE (nombre_categoria),
    CONSTRAINT chk_categoria_nombre CHECK (TRIM(nombre_categoria) <> '')
);

-- =============================================
-- 2. TABLA PLATO
-- =============================================

CREATE TABLE menu.plato (
    id_plato INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_categoria INTEGER NOT NULL,
    nombre_plato VARCHAR(100) NOT NULL,
    descripcion VARCHAR(500) NOT NULL DEFAULT '',
    precio_plato INTEGER NOT NULL,
    disponible BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT pk_plato PRIMARY KEY (id_plato),

    CONSTRAINT fk_plato_categoria
        FOREIGN KEY (id_categoria)
        REFERENCES menu.categoria (id_categoria),

    CONSTRAINT chk_plato_precio CHECK (precio_plato >= 0),
    CONSTRAINT chk_plato_nombre CHECK (TRIM(nombre_plato) <> '')
);

-- =============================================
-- 3. TABLA MENU_DIARIO
-- =============================================

CREATE TABLE menu.menu_diario (
    id_menu INTEGER GENERATED BY DEFAULT AS IDENTITY,
    fecha_menu DATE NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'BORRADOR',

    CONSTRAINT pk_menu_diario PRIMARY KEY (id_menu),
    CONSTRAINT uq_menu_diario_fecha UNIQUE (fecha_menu),

    CONSTRAINT chk_menu_diario_estado
        CHECK (estado IN ('BORRADOR', 'PUBLICADO', 'CERRADO'))
);

-- =============================================
-- 4. TABLA MENU_DETALLE
-- =============================================

CREATE TABLE menu.menu_detalle (
    id_menu_detalle INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_menu INTEGER NOT NULL,
    id_plato INTEGER NOT NULL,
    precio_menu INTEGER NOT NULL,
    disponible BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT pk_menu_detalle PRIMARY KEY (id_menu_detalle),

    CONSTRAINT fk_menu_detalle_menu
        FOREIGN KEY (id_menu)
        REFERENCES menu.menu_diario (id_menu)
        ON DELETE CASCADE,

    CONSTRAINT fk_menu_detalle_plato
        FOREIGN KEY (id_plato)
        REFERENCES menu.plato (id_plato),

    CONSTRAINT uq_menu_detalle_plato
        UNIQUE (id_menu, id_plato),

    CONSTRAINT chk_menu_detalle_precio CHECK (precio_menu >= 0)
);

-- =============================================
-- 5. TABLA PLANTILLA_MENU
-- =============================================

CREATE TABLE menu.plantilla_menu (
    id_plantilla INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre_plantilla VARCHAR(100) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT pk_plantilla_menu PRIMARY KEY (id_plantilla),
    CONSTRAINT uq_plantilla_menu_nombre UNIQUE (nombre_plantilla),

    CONSTRAINT chk_plantilla_menu_nombre
        CHECK (TRIM(nombre_plantilla) <> '')
);

-- =============================================
-- 6. TABLA PLANTILLA_DETALLE
-- =============================================

CREATE TABLE menu.plantilla_detalle (
    id_plantilla_detalle INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_plantilla INTEGER NOT NULL,
    id_plato INTEGER NOT NULL,

    CONSTRAINT pk_plantilla_detalle
        PRIMARY KEY (id_plantilla_detalle),

    CONSTRAINT fk_plantilla_detalle_plantilla
        FOREIGN KEY (id_plantilla)
        REFERENCES menu.plantilla_menu (id_plantilla)
        ON DELETE CASCADE,

    CONSTRAINT fk_plantilla_detalle_plato
        FOREIGN KEY (id_plato)
        REFERENCES menu.plato (id_plato),

    CONSTRAINT uq_plantilla_detalle_plato
        UNIQUE (id_plantilla, id_plato)
);

-- =============================================
-- 7. INDICES
-- =============================================

CREATE INDEX idx_plato_categoria
    ON menu.plato (id_categoria);

CREATE INDEX idx_menu_detalle_plato
    ON menu.menu_detalle (id_plato);

CREATE INDEX idx_plantilla_detalle_plato
    ON menu.plantilla_detalle (id_plato);

CREATE INDEX idx_menu_diario_estado
    ON menu.menu_diario (estado);
